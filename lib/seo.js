export function canonicalUrl(path = "/") {
  if (!path || path === "/") {
    return `${SITE_URL}/`;
  }

  const clean = path.startsWith("/") ? path : `/${path}`;
  return `${SITE_URL}${clean.endsWith("/") ? clean : `${clean}/`}`;
}

export function pageMeta({ title, description, path, image, type = "website" }) {
  const url = canonicalUrl(path);
  const ogImage = image || DEFAULT_OG_IMAGE;

  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      title,
      description,
      url,
      siteName: SITE_NAME,
      type,
      locale: "en_US",
      images: [{ url: ogImage, alt: title }],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [ogImage],
    },
  };
}

export function seoForPath(path, fallback) {
  const entry = PAGE_SEO[path] || fallback;

  if (!entry) {
    return pageMeta({
      title: SITE_NAME,
      description: PAGE_SEO["/"].description,
      path: path || "/",
    });
  }

  return pageMeta({ ...entry, path: path || "/" });
}

export function seoForBlog(post) {
  const planned = BLOG_SEO[post.slug];
  const title = planned?.title || `${post.title} | Albatroz Blog`;
  const description = planned?.description || post.excerpt;

  return pageMeta({
    title,
    description,
    path: `/blog/${post.slug}`,
    image: post.image,
    type: "article",
  });
}
